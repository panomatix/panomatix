function detect() {
  const saved = localStorage.getItem('pmx_lang');
  if (saved && LANGUAGES[saved]) return saved;
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = String(l).slice(0, 2).toLowerCase();
    if (LANGUAGES[base]) return base;
  }
  return 'en';
}

export let lang = detect();
document.documentElement.lang = lang;

export function setLang(l) {
  if (!LANGUAGES[l]) return;
  localStorage.setItem('pmx_lang', l);
  lang = l;
  document.documentElement.lang = l;
}

/** t('Page {p} / {n}', {p: 1, n: 3}) */
export function t(key, vars) {
  let s = DICT[lang]?.[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

/** Plural helper: tn(n, '{n} sign', '{n} signs') */
export const tn = (n, one, many) => t(n === 1 ? one : many, { n: n.toLocaleString(lang) });

export const fmtDateTime = (ts) => (ts ? new Date(ts * 1000).toLocaleString(lang, { dateStyle: 'medium', timeStyle: 'short' }) : '—');
